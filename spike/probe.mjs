import * as api from '@actual-app/api';
import fs from 'node:fs';
process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';
const t0 = Date.now();
const lap = (l) => console.log(`[${((Date.now()-t0)/1000).toFixed(2)}s] ${l}`);
fs.mkdirSync('./data', { recursive: true });
await api.init({ dataDir: './data', serverURL: process.env.ACTUAL_SERVER_URL, password: process.env.ACTUAL_PASSWORD });
lap('init ok');
const budgets = await api.getBudgets?.().catch(e => 'getBudgets n/a: ' + e.message);
console.log('budgets:', JSON.stringify(budgets).slice(0, 300));
const opts = process.env.ACTUAL_E2E_PASSWORD ? { password: process.env.ACTUAL_E2E_PASSWORD } : undefined;
await api.downloadBudget(process.env.ACTUAL_SYNC_ID, opts);
lap('downloadBudget ok');
const accounts = await api.getAccounts();
const cats = await api.getCategories();
const groups = await api.getCategoryGroups();
const payees = await api.getPayees();
lap(`meta: ${accounts.length} accounts, ${cats.length} cats, ${groups.length} groups, ${payees.length} payees`);
const t1 = Date.now();
const all = [];
for (const a of accounts.filter(a => !a.closed)) {
  const tx = await api.getTransactions(a.id, '2020-01-01', '2027-12-31');
  all.push(...tx);
}
lap(`getTransactions full history: ${all.length} tx in ${Date.now()-t1}ms`);
const t2 = Date.now();
const r = await api.runQuery(api.q('transactions').filter({ date: { $gte: '2020-01-01' } }).select(['id','date','amount','account','category','payee','notes']));
lap(`ActualQL full history: ${r.data.length} rows in ${Date.now()-t2}ms`);
const t3 = Date.now();
const par = await Promise.all(Array.from({ length: 20 }, () => api.runQuery(api.q('transactions').filter({ date: { $gte: '2026-09-01' } }).select(['id','amount']))));
lap(`20 parallel queries ok: ${par.map(x => x.data.length).join(',')} in ${Date.now()-t3}ms`);
const t4 = Date.now();
await api.sync();
lap(`sync() in ${Date.now()-t4}ms`);
await api.shutdown();
lap('shutdown ok');
